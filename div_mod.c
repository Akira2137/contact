#include <stdio.h>
int main(void)
{

printf("7 / 2    = %d\n", 7 / 2);
printf("-7 / 2   = %d\n", -7 / 2);
printf("7 / -2   = %d\n", 7 / -2);

printf("7 %% 2   = %d\n", 7 % 2);
printf("-7 %% 2  = %d\n", -7 % 2);
printf("7 %% -2  = %d\n", 7 % -2);

printf("7.0 / 2  = %f\n", 7.0 / 2);
printf("(double)7 / 2 = %f\n", (double)7 / 2);
}
